import { v } from "convex/values";
export const excerpt = v.object({
  path: v.string(),
  previousPath: v.union(v.string(), v.null()),
  blobSha: v.string(),
  change: v.string(),
  patch: v.string(),
});
export const contextFields = {
  workspaceId: v.id("workspaces"),
  actorId: v.id("users"),
  signalId: v.id("githubSignals"),
  repositoryId: v.id("githubRepositories"),
  generation: v.number(),
  connectionGeneration: v.number(),
  credentialGeneration: v.number(),
  operationKey: v.string(),
  paths: v.array(v.string()),
  createdAt: v.number(),
  admissionSequence: v.number(),
  state: v.union(
    v.literal("pending"),
    v.literal("ready"),
    v.literal("needs_context"),
    v.literal("failed"),
  ),
  excerpts: v.array(excerpt),
  hash: v.string(),
  errorCode: v.union(v.string(), v.null()),
  approvedHash: v.optional(v.string()),
  approvedAt: v.optional(v.number()),
  runId: v.union(v.id("agentRuns"), v.null()),
  accountId: v.union(v.id("socialAccounts"), v.null()),
  resultIdeaId: v.union(v.id("ideas"), v.null()),
  decision: v.union(
    v.literal("pending"),
    v.literal("maintenance"),
    v.literal("needs_context"),
    v.literal("relevant"),
  ),
  summary: v.string(),
  rationale: v.string(),
  novelty: v.string(),
  uncertainty: v.string(),
  references: v.array(v.string()),
  evidence: v.array(v.object({ path: v.string(), quote: v.string() })),
  outputHash: v.optional(v.string()),
};
