import { v } from "convex/values";
export const eventKind = v.union(
  ...(
    [
      "push",
      "release",
      "revoke_user",
      "revoke_install",
      "revoke_repositories",
    ] as const
  ).map(v.literal),
);
export const facts = v.object({
  kind: eventKind,
  installationId: v.string(),
  providerId: v.string(),
  fullName: v.string(),
  private: v.boolean(),
  identity: v.string(),
  ref: v.string(),
  before: v.string(),
  after: v.string(),
  created: v.boolean(),
  deleted: v.boolean(),
  forced: v.boolean(),
  commitCount: v.number(),
  releaseId: v.string(),
  tag: v.string(),
  prerelease: v.boolean(),
  providerAt: v.union(v.number(), v.null()),
  removed: v.array(v.string()),
  allRemoved: v.boolean(),
});
export const receiptFields = {
  eventKey: v.string(),
  digest: v.string(),
  guid: v.string(),
  facts,
  receivedAt: v.number(),
  admissionSequence: v.optional(v.number()),
  state: v.union(v.literal("pending"), v.literal("processed")),
  cursor: v.union(v.string(), v.null()),
  dueAt: v.number(),
  processedCount: v.number(),
  blockedCount: v.number(),
  aliasCount: v.number(),
  revocationSequence: v.number(),
  latestReceivedAt: v.number(),
  ambiguousRevocation: v.boolean(),
};
export const signalFields = {
  eventKey: v.string(),
  workspaceId: v.id("workspaces"),
  repositoryId: v.id("githubRepositories"),
  generation: v.number(),
  receiptId: v.id("githubWebhookReceipts"),
  digest: v.string(),
  guid: v.string(),
  kind: v.union(v.literal("push"), v.literal("release")),
  fullName: v.string(),
  private: v.boolean(),
  ref: v.string(),
  before: v.string(),
  after: v.string(),
  commitCount: v.number(),
  created: v.boolean(),
  deleted: v.boolean(),
  forced: v.boolean(),
  releaseId: v.string(),
  tag: v.string(),
  prerelease: v.boolean(),
  url: v.union(v.string(), v.null()),
  providerAt: v.union(v.number(), v.null()),
  receivedAt: v.number(),
  processedAt: v.number(),
  explicitRecovery: v.optional(
    v.object({
      actorId: v.id("users"),
      authorizedAt: v.number(),
      recoveryId: v.id("githubRecoveries"),
    }),
  ),
};
export const recoveryFields = {
  workspaceId: v.id("workspaces"),
  repositoryId: v.id("githubRepositories"),
  generation: v.number(),
  providerId: v.string(),
  installationId: v.string(),
  deliveryId: v.string(),
  guid: v.string(),
  event: v.union(v.literal("push"), v.literal("release")),
  deliveredAt: v.number(),
  providerStatus: v.union(v.number(), v.null()),
  state: v.union(
    v.literal("missing"),
    v.literal("requesting"),
    v.literal("accepted"),
    v.literal("unknown"),
    v.literal("processed"),
  ),
  sequence: v.number(),
  attempts: v.number(),
  leaseUntil: v.number(),
  notBefore: v.number(),
  updatedAt: v.number(),
  errorCode: v.union(v.string(), v.null()),
};
export const observedDelivery = v.object({
  deliveryId: v.string(),
  guid: v.string(),
  event: recoveryFields.event,
  installationId: v.string(),
  providerId: v.string(),
  deliveredAt: v.number(),
  providerStatus: v.union(v.number(), v.null()),
});
