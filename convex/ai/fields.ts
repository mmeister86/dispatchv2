import { v } from "convex/values";
export const generationPurpose = v.union(
  ...(["summary", "research", "draft", "plan"] as const).map(v.literal),
);
export const source = v.object({
  repositoryId: v.id("githubRepositories"),
  generation: v.number(),
});
export const policyFields = {
  key: v.literal("requesty-generation"),
  version: v.string(),
  enabled: v.boolean(),
  processingEvidence: v.string(),
  pricingEvidence: v.string(),
  model: v.string(),
  baseURL: v.literal("https://router.eu.requesty.ai/v1"),
  currency: v.string(),
  inputMicrosPerMillion: v.number(),
  outputMicrosPerMillion: v.number(),
  maxInputTokens: v.number(),
  maxOutputTokens: v.number(),
  maxAttempts: v.number(),
  maxToolSteps: v.number(),
  maxDurationMs: v.number(),
  purposes: v.array(generationPurpose),
};
export const budgetFields = {
  key: v.string(),
  policyVersion: v.string(),
  currency: v.string(),
  scope: v.union(
    v.literal("provider"),
    v.literal("workspace"),
    v.literal("account"),
  ),
  workspaceId: v.optional(v.id("workspaces")),
  accountId: v.optional(v.id("socialAccounts")),
  purposes: v.array(generationPurpose),
  approvedBy: v.optional(v.id("users")),
  expiresAt: v.number(),
  limitMicros: v.number(),
  heldMicros: v.number(),
  spentMicros: v.number(),
};
export const runFields = {
  workspaceId: v.id("workspaces"),
  accountId: v.id("socialAccounts"),
  actorId: v.id("users"),
  purpose: generationPurpose,
  policyVersion: v.string(),
  promptVersion: v.string(),
  policyFingerprint: v.string(),
  accountConnectionSequence: v.number(),
  sources: v.array(source),
  threadId: v.string(),
  promptMessageId: v.string(),
  generation: v.number(),
  state: v.union(
    v.literal("ready"),
    v.literal("running"),
    v.literal("completed"),
    v.literal("stopped"),
    v.literal("failed"),
  ),
  executionKey: v.union(v.string(), v.null()),
  deadline: v.number(),
  attempts: v.number(),
  toolSteps: v.number(),
  budgetIds: v.array(v.id("aiBudgets")),
  createdAt: v.number(),
  errorCode: v.union(v.string(), v.null()),
};
export const attemptFields = {
  runId: v.id("agentRuns"),
  workspaceId: v.id("workspaces"),
  key: v.string(),
  generation: v.number(),
  budgetIds: v.array(v.id("aiBudgets")),
  reservedMicros: v.number(),
  heldMicros: v.number(),
  currency: v.string(),
  policyVersion: v.string(),
  model: v.string(),
  provider: v.literal("requesty"),
  inputMicrosPerMillion: v.number(),
  outputMicrosPerMillion: v.number(),
  state: v.union(v.literal("sent"), v.literal("settled"), v.literal("unknown")),
  sentAt: v.number(),
  settledAt: v.union(v.number(), v.null()),
  inputTokens: v.union(v.number(), v.null()),
  outputTokens: v.union(v.number(), v.null()),
  estimatedMicros: v.union(v.number(), v.null()),
  billedMicros: v.union(v.number(), v.null()),
  reportedCost: v.union(v.number(), v.null()),
  reportedCurrency: v.null(),
  reportedCostInvalid: v.boolean(),
  errorCode: v.union(v.string(), v.null()),
};
